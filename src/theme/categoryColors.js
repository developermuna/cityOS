export const hexToRgba = (hex, alpha = 0.8) => {
  if (!hex) return `rgba(128, 0, 32, ${alpha})`;
  let cleanHex = hex.replace('#', '');
  if (cleanHex.length === 3) {
    cleanHex = cleanHex.split('').map(c => c + c).join('');
  }
  const r = parseInt(cleanHex.substring(0, 2), 16) || 0;
  const g = parseInt(cleanHex.substring(2, 4), 16) || 0;
  const b = parseInt(cleanHex.substring(4, 6), 16) || 0;
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
};

export const getCategoryTheme = (tabId) => {
  const theme = CATEGORY_COLORS[tabId] || CATEGORY_COLORS.cityos;
  return {
    ...theme,
    rgba80: hexToRgba(theme.hex, 0.8),
    rgba70: hexToRgba(theme.hex, 0.8)
  };
};
